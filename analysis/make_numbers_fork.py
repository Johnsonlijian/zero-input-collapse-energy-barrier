"""Emit numbers_fork.tex: repeat-run (fork) audit macros from fork_rate.csv.
Standalone so the manuscript builds before the next full make_numbers53 pass;
the same block is also emitted by make_numbers53.py at regen (identical names,
numbers.tex inclusion order keeps the fork file authoritative: macros match)."""
import csv, statistics, sys
from pathlib import Path

CSV = Path(r"E:\n0r53\analysis\fork_rate.csv")
if not CSV.exists():
    CSV = Path("/mnt/e/n0r53/analysis/fork_rate.csv")
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else CSV.parent / "numbers_fork.tex"

rows = list(csv.DictReader(CSV.open(encoding="utf-8")))

def dev(r):
    if not (r["W_canon"] and r["W_r1"] and r["W_r2"]):
        return None
    w0 = float(r["W_canon"])
    if abs(w0) == 0:
        return None
    s = (max(w0, float(r["W_r1"]), float(r["W_r2"]))
         - min(w0, float(r["W_r1"]), float(r["W_r2"]))) / abs(w0)
    flip = r["lim_r1"] != r["lim_canon"] or r["lim_r2"] != r["lim_canon"]
    return s, flip

done = [r for r in rows if dev(r) is not None]
d = [dev(r) for r in done]
ndev = sum(1 for s, fp in d if s > 1e-6 or fp)
nflip = sum(1 for s, fp in d if fp)
spreads = [s for s, fp in d if s > 1e-6 or fp]
bare = [dev(r) for r in done if r["model"].endswith("B")]
baredev = sum(1 for x in bare if x and (x[0] > 1e-6 or x[1]))
cg = [dev(r) for r in done if r["model"].endswith("CG")]
cgdev = sum(1 for x in cg if x and (x[0] > 1e-6 or x[1]))
miss_r = sum(1 for r in rows if r["W_canon"] and (not r["W_r1"] or not r["W_r2"]))
miss_c = sum(1 for r in rows if not r["W_canon"] and (r["W_r1"] or r["W_r2"]))
miss_c_bare = sum(1 for r in rows if not r["W_canon"] and (r["W_r1"] or r["W_r2"]) and r["model"].endswith("B"))
nobar = sum(1 for r in rows if not r["W_canon"] and not r["W_r1"] and not r["W_r2"])

L = ["% AUTO-GENERATED by make_numbers_fork.py from fork_rate.csv -- do not edit by hand", ""]
for n, v in [("forkNpush", len(rows)), ("forkNdone", len(done)), ("forkDev", ndev),
             ("forkDevPct", round(100 * ndev / len(done))), ("forkFlip", nflip),
             ("forkSpreadMed", f"{statistics.median(spreads) * 100:.2f}"),
             ("forkSpreadMax", f"{max(spreads) * 100:.1f}"),
             ("forkBareDev", baredev), ("forkBareN", len(bare)),
             ("forkCGN", len(cg)), ("forkCGDevPct", round(100 * cgdev / len(cg))),
             ("forkMissR", miss_r), ("forkMissC", miss_c), ("forkMissCBare", miss_c_bare), ("forkNoBar", nobar)]:
    L.append(f"\\newcommand{{\\{n}}}{{{v}}}")
OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"{len(L)} lines -> {OUT}")
