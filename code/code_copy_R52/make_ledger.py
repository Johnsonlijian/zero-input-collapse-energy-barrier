def main() -> None:
    nums = (ROOT / "manuscript" / "numbers.tex").read_text(encoding="utf-8")
    val = dict(re.findall(r"\\newcommand\{\\Num([A-Za-z]+)\}\{(.*)\}", nums))
    out = ["# R52 claim-evidence ledger", "",
           "Generated by `code/make_ledger.py` from `manuscript/numbers.tex`; every value is the one",
           "printed in the compiled manuscript. `??` marks a value whose source result is missing.", ""]
    for i, (claim, macros, where, src) in enumerate(CLAIMS, 1):
        vals = ", ".join(f"`{m}` = {val.get(m, 'UNDEFINED')}" for m in macros)
        flag = " **(incomplete)**" if any(val.get(m, "??") in ("??", "UNDEFINED") for m in macros) else ""
        out += [f"## C{i}. {claim}{flag}", "", f"- Numbers: {vals}", f"- Shown in: {where}",
                f"- Source: {src}", ""]
    (ROOT / "notes" / "CLAIM_EVIDENCE_LEDGER.md").write_text("\n".join(out), encoding="utf-8")
    print("ledger written;", sum("(incomplete)" in s for s in out), "incomplete claims")


if __name__ == "__main__":
    main()
